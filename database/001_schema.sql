-- Separado de empleados: una cuenta puede ser auditor o call center.
-- Los roles nunca se toman de user_metadata ni del formulario de registro.
create table public.perfiles (
  id_usuario uuid primary key references auth.users(id),
  rol text not null check (rol in ('ADMIN','GERENTE','VENDEDOR','BODEGA','CAJERO','CALL_CENTER','AUDITOR')),
  id_sucursal bigint references public.sucursales,
  activo boolean not null default true,
  check (rol in ('ADMIN','CALL_CENTER','AUDITOR') or id_sucursal is not null)
);

create table public.empleados (
  id_empleado bigint generated by default as identity primary key,
  codigo varchar(30) not null unique,
