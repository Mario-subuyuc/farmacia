-- Estas funciones leen perfiles como propietario para evitar RLS recursivo.
create function privado.permitido(p_roles text[], p_sucursal bigint default null)
returns boolean language sql stable security definer set search_path = public, pg_temp as $$
  select exists(select 1 from public.perfiles
    where id_usuario = auth.uid() and activo
    and (rol = 'ADMIN' or rol = any(p_roles))
    and (p_sucursal is null or rol in ('ADMIN','AUDITOR','CALL_CENTER') or id_sucursal = p_sucursal));
$$;
create function privado.exigir(p_roles text[], p_sucursal bigint default null)
returns void language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if not privado.permitido(p_roles,p_sucursal) then
    raise exception 'No tienes permiso para esta operación o sucursal' using errcode = '42501';
  end if;
end; $$;

-- Histórico automático. No se permite editar ni eliminar auditoría desde la API.
create function privado.auditar() returns trigger
language plpgsql security definer set search_path = public, pg_temp as $$
declare v_antes jsonb; v_despues jsonb; v_fila jsonb; v_sucursal bigint;
begin
  if tg_op <> 'INSERT' then v_antes := to_jsonb(old); end if;
  if tg_op <> 'DELETE' then v_despues := to_jsonb(new); end if;
  v_fila := coalesce(v_despues,v_antes);
  v_sucursal := (v_fila->>'id_sucursal')::bigint;
  -- Los detalles heredan la sucursal de su cabecera para no filtrar datos ajenos.
  if tg_table_name='detalle_venta' then select id_sucursal into v_sucursal from public.ventas where id_venta=(v_fila->>'id_venta')::bigint; end if;
  if tg_table_name='detalle_pedido' then select id_sucursal into v_sucursal from public.pedidos where id_pedido=(v_fila->>'id_pedido')::bigint; end if;
  if tg_table_name='reservas_pedido' then select id_sucursal into v_sucursal from public.inventario where id_inventario=(v_fila->>'id_inventario')::bigint; end if;
  if tg_table_name='detalle_planilla' then select id_sucursal into v_sucursal from public.planillas where id_planilla=(v_fila->>'id_planilla')::bigint; end if;
  if tg_table_name in ('traslados','detalle_traslado') then
    if tg_table_name='traslados' then v_sucursal := (v_fila->>'id_sucursal_origen')::bigint;
    else select id_sucursal_origen into v_sucursal from public.traslados where id_traslado=(v_fila->>'id_traslado')::bigint; end if;
  end if;
  insert into public.auditoria(tabla,registro,accion,id_sucursal,actor,antes,despues)
  values(tg_table_name, v_fila->>tg_argv[0], tg_op,
    v_sucursal, auth.uid(), v_antes,v_despues);
  return coalesce(new,old);
end; $$;

do $$ declare t text; pk text; begin
  for t,pk in select * from (values
    ('sucursales','id_sucursal'),('perfiles','id_usuario'),('empleados','id_empleado'),
    ('medicamentos','id_medicamento'),('inventario','id_inventario'),('stock_minimos','id_stock'),
    ('clientes','id_cliente'),('pedidos','id_pedido'),('detalle_pedido','id_detalle'),
    ('reservas_pedido','id_reserva'),('ventas','id_venta'),('detalle_venta','id_detalle'),
    ('traslados','id_traslado'),('detalle_traslado','id_detalle'),
    ('movimientos_medicamentos','id_movimiento'),('movimientos_caja','id_movimiento'),
    ('planillas','id_planilla'),('detalle_planilla','id_detalle'),('activos','id_activo')
  ) as tablas(tabla,clave) loop
    execute format('alter table public.%I enable row level security',t);
    execute format('create trigger historial after insert or update or delete on public.%I for each row execute function privado.auditar(%L)',t,pk);
    execute format('revoke all on public.%I from anon,authenticated',t);
    execute format('grant select on public.%I to authenticated',t);
    execute format('grant all on public.%I to service_role',t);
    if t<>'perfiles' then
      execute format('grant all on sequence %s to service_role',pg_get_serial_sequence('public.'||t,pk));
    end if;
    if t in ('sucursales','empleados','medicamentos','stock_minimos','clientes','activos') then
      execute format('grant usage,select on sequence %s to authenticated',pg_get_serial_sequence('public.'||t,pk));
    end if;
  end loop;
end; $$;
