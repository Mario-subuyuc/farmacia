create table public.sucursales (
  id_sucursal bigint generated by default as identity primary key,
  codigo varchar(30) not null unique,
  nombre varchar(100) not null,
  departamento varchar(100) not null,
  direccion varchar(255) not null,
  telefono varchar(20),
  tipo varchar(20) not null check (tipo in ('FARMACIA','STAND')),
  estado varchar(20) not null default 'ACTIVA' check (estado in ('ACTIVA','INACTIVA')),
  latitud numeric(10,7) not null check (latitud between -90 and 90),
  longitud numeric(10,7) not null check (longitud between -180 and 180),
  radio_entrega_km numeric(8,2) not null default 10 check (radio_entrega_km > 0),
  preparacion_minutos integer not null default 15 check (preparacion_minutos >= 0),
  velocidad_kmh numeric(8,2) not null default 20 check (velocidad_kmh > 0),
  acepta_pedidos boolean not null default true
