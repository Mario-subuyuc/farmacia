begin;
create table public.notificaciones(id_notificacion bigint generated by default as identity primary key,id_pedido bigint not null references public.pedidos,
 id_sucursal bigint not null references public.sucursales,destino varchar(150) not null,evento text not null,
 estado text not null default 'PENDIENTE' check(estado in ('PENDIENTE','ENVIANDO','ENVIADO','ERROR')),
 intentos integer not null default 0,proximo_intento timestamptz not null default now(),creado_en timestamptz not null default now(),ultimo_error varchar(255));
alter table public.notificaciones enable row level security;
grant select on public.notificaciones to authenticated;
grant all on public.notificaciones to service_role;
grant usage,select on sequence public.notificaciones_id_notificacion_seq to service_role;
create policy lectura_notificaciones on public.notificaciones for select to authenticated using(privado.permitido(array['GERENTE','AUDITOR'],id_sucursal));
create function privado.encolar_pedido(p_id bigint,p_evento text) returns void language sql security definer set search_path=pg_catalog,public as $$
 insert into public.notificaciones(id_pedido,id_sucursal,destino,evento) select p.id_pedido,p.id_sucursal,c.email,p_evento from public.pedidos p join public.clientes c using(id_cliente) where p.id_pedido=p_id and c.email is not null;
$$;
revoke all on function privado.encolar_pedido(bigint,text) from public,anon,authenticated;
create function privado.notificar_portal() returns trigger language plpgsql security definer set search_path=pg_catalog,public as $$
begin
 if tg_table_name='pedidos_portal' then perform privado.encolar_pedido(new.id_pedido,'CONFIRMADO');
 elsif new.estado<>old.estado then perform privado.encolar_pedido(new.id_pedido,new.estado);
 elsif new.receta_estado<>old.receta_estado then perform privado.encolar_pedido(new.id_pedido,'RECETA_'||new.receta_estado);
 elsif new.estado_pago<>old.estado_pago then perform privado.encolar_pedido(new.id_pedido,'PAGO_'||new.estado_pago);end if;
 return new;
end $$;
create trigger aviso_confirmacion after insert on privado.pedidos_portal for each row execute function privado.notificar_portal();
create trigger aviso_cambio after update on public.pedidos for each row execute function privado.notificar_portal();
commit;
